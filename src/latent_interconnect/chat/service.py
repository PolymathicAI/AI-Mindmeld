class ChatError(ValueError):
    """A request the service refuses; its message is shown to the user."""


@dataclass
class _Connector:
    """A loaded connector: its checked checkpoint, its loader over the cached and the live embeddings."""

    entry: ChatConnector
    checked: CheckedConnector
    table: dict[str, str]
    pinned: list[EmbeddingReader]
    loader: InputLoader
    live_values: dict[str, str] = field(default_factory=dict)
    live: list[EmbeddingReader] = field(default_factory=list)
    lock: threading.Lock = field(default_factory=threading.Lock)


@dataclass
class _Phase:
    key: str
    label: str
    expected_s: float
    status: str = "pending"
    started: float | None = None
    ended: float | None = None
    detail: str | None = None


class ChatService:
    """Serve one receiver of a chat config.

    Args:
        config: the chat deployment.
        receiver: the receiver id to serve (a key of ``config.receivers``).
        workspace: the workspace (pins and the production store, read only).
        pool: the live encoders; its store is chat's own, where everything chat writes goes.
        deployment: the id ``/api/health`` reports (the front door matches it with the deployment's lease).
        options: execution options for the generation backend (``receivers.open_generation``).
        construction: values the backend takes from code (a built model, in tests).
        max_tokens_cap: a lower answer cap than the config's ``max_tokens_cap`` (the default answer cap is lowered to
            it too), e.g. a measured local envelope's (set by the launcher); None: the config's.
        max_prompt_tokens: the longest rendered prompt served (a longer one is refused before generation), e.g. a
            measured local envelope's; None: up to the receiver's ``context``.
        serial_requests: serve one whole request at a time, its live encodings with its generation (and a
            placeholder check, which can encode, waits too), e.g. a measured local envelope's concurrency 1; False:
            only generation is one request at a time, and another request's live encoding can overlap it.
        answer: the receiver's answer convention (``configs/answers/``), which offers the Yes/No readout where the
            receiver's score backend is its generate backend (:attr:`yes_no_offered`); None: not offered.

    Raises:
        ValueError: if the config has no such receiver, the pool's store and the workspace's overlap (one is, or is
            inside, the other), or a ``max_model_len`` option is below the receiver's ``context`` (before any load).
    """

    def __init__(
        self,
        config: ChatConfig,
        receiver: str,
        workspace: Workspace,
        pool: EncoderPool,
        *,
        deployment: str | None = None,
        options: Mapping[str, str] | None = None,
        construction: Mapping[str, Any] | None = None,
        max_tokens_cap: int | None = None,
        max_prompt_tokens: int | None = None,
        serial_requests: bool = False,
        answer: AnswerConvention | None = None,
    ) -> None:
        if receiver not in config.receivers:
            raise ValueError(f"receiver {receiver!r} is not in the chat config: {sorted(config.receivers)}")
        chat, production = pool.store.root.resolve(), workspace.artifacts.root.resolve()
        if chat.is_relative_to(production) or production.is_relative_to(chat):
            raise ValueError(
                f"chat writes go to its own store, apart from the workspace's: {chat} and {production} overlap"
            )
        requested = (options or {}).get("max_model_len")
        if requested is not None and int(requested) < config.receivers[receiver].context:
            raise ValueError(
                f"max_model_len={requested} is below the config's context {config.receivers[receiver].context}"
            )
        if max_tokens_cap is not None and max_tokens_cap < config.max_tokens_cap:
            defaults = config.defaults.model_copy(
                update={"max_tokens": min(config.defaults.max_tokens, max_tokens_cap)}
            )
            config = config.model_copy(update={"max_tokens_cap": max_tokens_cap, "defaults": defaults})
        self.max_prompt_tokens = max_prompt_tokens
        self.config, self.receiver_id, self.entry = config, receiver, config.receivers[receiver]
        self.ws, self.pool, self.deployment = workspace, pool, deployment
        self.options, self.construction = dict(options or {}), dict(construction or {})
        self.answer = answer
        self.backend: GenerationBackend | None = None
        self.scorer: ScoringBackend | None = None
        self.renderer: Renderer | None = None
        self.connectors: dict[str, _Connector] = {}
        self.errors: dict[str, str] = {}
        self.failed: str | None = None
        self.started = time.time()
        self.phases = [
            _Phase("connectors", "Loading the connectors and their cached embeddings", 30.0),
            _Phase("receiver", f"Loading {self.entry.label}", self.entry.expected_load_s),
        ]
        self._generation = threading.Lock()
        self._serial = threading.Lock() if serial_requests else None
        self._stops: dict[str, threading.Event] = {}

    # -- start-up ----------------------------------------------------------------------------------------------------

    def load(self) -> None:
        """Load the connectors, then the receiver (blocking; the server runs it in a thread and answers meanwhile).

        A connector that cannot be served (its checkpoint pin is missing, the checkpoint is of another step or receiver,
        its embeddings do not fit its recipe) is recorded with its error and refused in requests; the others serve. A
        receiver that fails to load fails the service.
        """
        self._run_phase("connectors", self._load_connectors)
        self._run_phase("receiver", self._load_receiver)

    def _run_phase(self, key: str, body: Any) -> None:
        phase = next(p for p in self.phases if p.key == key)
        if self.failed is not None:
            phase.status = "skipped"
            return
        phase.status, phase.started = "running", time.time()
        try:
            body()
        except Exception as err:
            phase.status, phase.detail = "failed", f"{type(err).__name__}: {err}"
            self.failed = f"{phase.label}: {phase.detail}"
        else:
            phase.status = "done"
        phase.ended = time.time()

    def _load_connectors(self) -> None:
        pins = self.ws.pins()
        tables: dict[str, dict[str, str]] = {}
        for cid, entry in sorted(self.entry.connectors.items()):
            try:
                pin = pins.get(entry.checkpoint_pin)
                if pin is None:
                    raise ChatError(f"its checkpoint pin {entry.checkpoint_pin!r} is missing")
                store = self.ws.artifacts
                checked = checked_connector(
                    store,
                    store.ref(pin.sha256),
                    receiver=self.entry.receiver.name,
                    step=entry.step,
                    what=f"checkpoint {entry.checkpoint_pin!r}",
                )
                domain = entry.run.domain
                if domain.digest() not in tables:
                    values = self.ws.domain(domain).objects()["value"]
                    tables[domain.digest()] = {str(k): str(v) for k, v in values.items()}
                pinned = [EmbeddingReader(store, store.ref(d)) for d in entry.run.embeddings]
                table = tables[domain.digest()]
                loader = checked.loader(pinned, self._consumed(entry, table))
                self.connectors[cid] = _Connector(entry, checked, table, pinned, loader)
            except Exception as err:
                self.errors[cid] = f"{type(err).__name__}: {err}"

    def _load_receiver(self) -> None:
        spec = self.entry.receiver
        self.renderer = open_renderer(spec)
        self.backend = open_generation(
            spec, generation_plan=self.entry.generation_plan, options=self.options, **self.construction
        )
        limit = getattr(self.backend, "max_model_len", None)  # a backend with an engine limit (kimi-vllm)
        if limit is not None and limit < self.entry.context:
            raise ValueError(
                f"the backend holds {limit} tokens, below the config's context {self.entry.context} "
                "(the launcher passes max_model_len=<context>)"
            )
        if self.yes_no_offered:
            assert self.answer is not None
            self.answer.policy().ids(self.renderer.token_id)  # each answer one token, or the load fails here
            pads = bool(getattr(backend_class(spec, "score"), "pads_every_batch", False))
            model = cast(Any, self.backend).model  # the generate backend is the score backend (hf): its model
            self.scorer = open_scoring(spec, plan=BatchPlan(pad_every_batch=pads), model=model)

    def _consumed(self, entry: ChatConnector, values: Mapping[str, str]) -> Consumed:
        """The values a connector's loader checks its vectors against: the domain's, and the live objects' own."""
        domain = entry.run.domain
        # the production root: its staging area holds the cached embeddings' object lists; a live artifact's list
        # (in chat's store) is rebuilt from these values instead (encoders.loader.Consumed)
        return Consumed(f"{domain.name} {domain.data[:12]}", values, self.ws.artifacts.root)

    @property
    def yes_no_offered(self) -> bool:
        """Whether Yes/No requests are served: an answer convention, and a receiver scored by its generation engine."""
        backends = self.entry.receiver.backends
        return self.answer is not None and backends.get("score") == backends.get("generate")

    @property
    def ready(self) -> bool:
        """Every phase done: requests are served."""
        return self.failed is None and all(p.status == "done" for p in self.phases)

    # -- views -------------------------------------------------------------------------------------------------------

    def config_view(self) -> dict[str, Any]:
        """``/api/config``: the deployed receiver, the others the config offers, its connectors, defaults and limits."""
        connectors = []
        for cid, entry in sorted(self.entry.connectors.items()):
            inputs = self.config.inputs[entry.run.domain.name]
            env = entry.run.encoder.environment
            view: dict[str, Any] = {
                "id": cid,
                "label": entry.label,
                "domain": entry.run.domain.name,
                "input_types": [inputs.id, inputs.value],
                "k": entry.run.connector.k,
                "encoder": entry.run.encoder.name,
                "environment": env,
                "operational_only": entry.operational_only,
                "status": "error" if cid in self.errors else self.pool.status(env),
            }
            if cid in self.errors:
                view["error"] = self.errors[cid]
            connectors.append(view)
        receivers = [
            {"id": r, "label": e.label, "deployed": r == self.receiver_id}
            for r, e in sorted(self.config.receivers.items())
        ]
        defaults = self.config.defaults.model_dump() | {"max_tokens_cap": self.config.max_tokens_cap}
        return {
            "model": self.entry.label,
            "receiver": self.receiver_id,
            "receivers": receivers,
            "engine": self.entry.receiver.backends["generate"],
            "thinking": self.entry.receiver.thinking_close is not None
            or "thinking" in self.entry.receiver.template_kwargs,
            "connectors": connectors,
            "yes_no": None if not self.yes_no_offered else self.answer.model_dump(),  # type: ignore[union-attr]
            "defaults": defaults,
            "ready": self.ready,
            "max_model_len": self.entry.context,
            "limits": {
                "max_placeholders": self.config.max_placeholders,
                "max_prompt_tokens": self.max_prompt_tokens,
                "max_len": {i.value: i.max_chars for i in self.config.inputs.values()},
            },
        }

    def health(self) -> dict[str, Any]:
        """``/api/health``: readiness, the start-up phases and the encoders' states."""
        now = time.time()
        phases = []
        for p in self.phases:
            view: dict[str, Any] = {k: getattr(p, k) for k in ("key", "label", "expected_s", "status", "detail")}
            if p.started is not None:
                view["elapsed_s"] = round((p.ended or now) - p.started, 1)
            phases.append(view)
        current = next((p.label for p in self.phases if p.status == "running"), None)
        envs = sorted({e.run.encoder.environment for e in self.entry.connectors.values()})
        return {
            "ok": True,
            "ready": self.ready,
            "job": self.deployment,
            "receiver": self.receiver_id,
            "engine": self.entry.receiver.backends["generate"],
            "encoders": {e: self.pool.status(e) for e in envs},
            "active_requests": len(self._stops),  # registered chat requests, running or waiting (the door's picker)
            "startup": {
                "phases": phases,
                "current": current,
                "chat_open": self.ready,
                "failed": self.failed,
                "uptime_s": round(now - self.started),
            },
        }

    # -- placeholders ------------------------------------------------------------------------------------------------

    def _connector(self, cid: str) -> _Connector:
        if cid in self.errors:
            raise ChatError(f"connector {cid!r} is unavailable: {self.errors[cid]}")
        if cid not in self.connectors:
            raise ChatError(f"unknown connector {cid!r}; this receiver serves {sorted(self.entry.connectors)}")
        return self.connectors[cid]

    def needs_encoder(self, cid: str, input_type: str, value: str) -> bool:
        """Whether resolving this input could start a live encoding (a raw value, or an id the cache lacks)."""
        c = self._connector(cid)
        inputs = self.config.inputs[c.entry.run.domain.name]
        return input_type != inputs.id or bool(c.loader.missing(["".join(value.split())]))

    def resolve(self, cid: str, input_type: str, value: str) -> tuple[str, str]:
        """Return the object a placeholder input is, and its source (``cache`` or ``live``), encoding it if needed.

        Raises:
            ChatError: for an unknown or unavailable connector, an input type the connector's domain does not take, an
                empty or too long value, an id the domain lacks, a failed encoding, or an object the loader refuses.
        """
        c = self._connector(cid)
        inputs = self.config.inputs[c.entry.run.domain.name]
        value = "".join(value.split())
        if not value:
            raise ChatError("the value is empty")
        if input_type == inputs.id:
            if value not in c.table:
                raise ChatError(f"{value!r} is not an object of the {c.entry.run.domain.name} domain")
            oid, raw = value, c.table[value]
        elif input_type == inputs.value:
            if len(value) > inputs.max_chars:
                raise ChatError(f"a {input_type} is at most {inputs.max_chars} characters, not {len(value)}")
            oid, raw = f"chat-{hashlib.sha256(value.encode()).hexdigest()[:16]}", value
        else:
            raise ChatError(f"connector {cid!r} takes input types {[inputs.id, inputs.value]}, not {input_type!r}")
        with c.lock:
            if oid in c.live_values or not c.loader.missing([oid]):
                return oid, "live" if oid in c.live_values else "cache"
            recipes = [r for r in (c.checked.encoder, c.checked.append_encoder) if r is not None]
            try:
                refs = [self.pool.encode(r, [RawObject(oid, raw)]) for r in recipes]
            except EncoderError as err:
                raise ChatError(f"encoding failed: {err}") from err
            known = {r.root for r in c.live}
            new = [EmbeddingReader(self.pool.store, ref) for ref in refs]
            live = c.live + [r for r in new if r.root not in known]
            values = {**c.live_values, oid: raw}
            loader = c.checked.loader(c.pinned + live, self._consumed(c.entry, ChainMap(values, c.table)))
            if missing := loader.missing([oid]):
                raise ChatError(f"the encoded object is refused: {missing[oid]}")
            c.live, c.live_values, c.loader = live, values, loader
            return oid, "live"

    def check(self, body: Mapping[str, Any]) -> dict[str, Any]:
        """``/api/placeholder/check``: resolve one placeholder input (encoding it if needed) without generating."""
        try:
            fields = [body.get(f) for f in ("connector", "input_type", "value")]
            if not all(isinstance(f, str) for f in fields):
                raise ChatError("connector, input_type and value must be strings")
            with self._serial or contextlib.nullcontext():
                oid, source = self.resolve(*(str(f) for f in fields))
        except ChatError as err:
            return {"ok": False, "key": None, "info": None, "error": str(err)}
        return {"ok": True, "key": oid, "info": {"object": oid, "source": source}, "error": None}

    # -- requests ----------------------------------------------------------------------------------------------------

    def stop_event(self, rid: str) -> threading.Event:
        """Return a request's stop event, registering the request (the server does so before it starts it)."""
        return self._stops.setdefault(rid, threading.Event())

    def stop(self, rid: str) -> None:
        """Stop a registered request (``/api/stop``) at whatever stage it is in; an unknown id is ignored."""
        if (event := self._stops.get(rid)) is not None:
            event.set()

    def events(self, body: Mapping[str, Any], rid: str) -> Generator[dict[str, Any], None, None]:
        """Serve one request: yield its events (``status``, ``reasoning``, ``content``, then ``done`` or ``error``).

        Blocking (the server iterates it in a thread). Closing the iterator stops the request.
        """
        stop = self.stop_event(rid)
        t0 = time.monotonic()
        try:
            yield from (self._events if self._serial is None else self._serially)(body, rid, stop, t0)
        except ValidationError as err:
            message = "; ".join(f"{'.'.join(map(str, e['loc']))}: {e['msg']}" for e in err.errors())
            yield {"type": "error", "message": f"invalid request: {message}", "request_id": rid}
        except (ChatError, KeyError, ValueError) as err:
            yield {"type": "error", "message": str(err).strip("'\""), "request_id": rid}
        except Exception as err:
            yield {"type": "error", "message": f"server error: {type(err).__name__}: {err}", "request_id": rid}
        finally:
            self._stops.pop(rid, None)

    def _serially(
        self, body: Mapping[str, Any], rid: str, stop: threading.Event, t0: float
    ) -> Iterator[dict[str, Any]]:
        """``_events`` once the request before has finished (``serial_requests``): one whole request at a time."""
        assert self._serial is not None
        while not self._serial.acquire(timeout=0.25):
            if stop.is_set():
                yield _done(rid, "abort", timings={"total_s": round(time.monotonic() - t0, 3)})
                return
        try:
            yield from self._events(body, rid, stop, t0)
        finally:
            self._serial.release()

    def _events(self, body: Mapping[str, Any], rid: str, stop: threading.Event, t0: float) -> Iterator[dict[str, Any]]:
        if not self.ready or self.backend is None or self.renderer is None:
            why = self.failed or f"{self.entry.label} is still loading"
            raise ChatError(f"{why}; you can write messages and add placeholders meanwhile")
        request = ChatRequest.model_validate(dict(body))
        if request.readout == "yes_no":
            yield from self._yes_no(request, rid, stop, t0)
            return
        messages, used = request.conversation(self.config.max_placeholders)
        params, thinking = self._params(request)
        bindings: dict[str, SlotBinding] = {}
        injections: dict[str, dict[str, Any]] = {}
        for p in used:
            if stop.is_set():
                break
            yield from self._bind(request, p, rid, bindings, injections)
        embed_s = time.monotonic() - t0
        if stop.is_set():
            yield _done(rid, "abort", timings={"total_s": round(time.monotonic() - t0, 3)})
            return
        prompt = self.renderer.render(Conversation(messages, thinking=thinking), bindings)
        n_prompt = len(prompt.input_ids)
        if n_prompt >= self.entry.context:
            raise ChatError(f"the conversation renders to {n_prompt} tokens, over the context {self.entry.context}")
        if self.max_prompt_tokens is not None and n_prompt > self.max_prompt_tokens:
            raise ChatError(
                f"the conversation renders to {n_prompt} tokens, over this deployment's prompt limit of "
                f"{self.max_prompt_tokens} (its measured envelope)"
            )
        params = params.model_copy(update={"max_new_tokens": min(params.max_new_tokens, self.entry.context - n_prompt)})
        sources: dict[str, WriteSource] = {}
        for cid in sorted({b.connector for b in bindings.values()}):
            c = self.connectors[cid]
            objects = sorted({b.object_id for b in bindings.values() if b.connector == cid})
            sources[cid], _ = c.checked.source(c.loader, objects, self.pool.store, banked=self.backend.reads_banks)
        yield _status(rid, "prefill", f"{n_prompt} prompt tokens", prompt_tokens=n_prompt)
        while not self._generation.acquire(timeout=0.25):  # one request at a time
            if stop.is_set():
                yield _done(rid, "abort", prompt_tokens=n_prompt, timings={"total_s": round(time.monotonic() - t0, 3)})
                return
        try:
            prepared = _Prepared(prompt, sources, params, thinking, injections, t0, embed_s)
            yield from self._generate(rid, prepared, stop)
        finally:
            self._generation.release()

    def _yes_no(self, request: ChatRequest, rid: str, stop: threading.Event, t0: float) -> Iterator[dict[str, Any]]:
        """Score the request's last user turn alone as a Yes/No question (the module docstring): one ``yes_no`` event.

        The request's earlier turns, system message, thinking mode and sampling are not used.
        """
        if self.scorer is None or self.answer is None:
            backends = self.entry.receiver.backends
            why = (
                "this server was started without an answer convention (aimm-chat serve --yes-no ANSWER.yaml)"
                if self.answer is None
                else f"its score backend {backends.get('score')!r} is not its generate backend {backends['generate']!r}"
            )
            raise ChatError(f"{self.entry.label} offers no Yes/No readout here: {why}")
        assert self.renderer is not None
        alone = request.model_copy(update={"messages": request.messages[-1:], "system": ""})
        (message,), used = alone.conversation(self.config.max_placeholders)
        if not message.content.strip():
            raise ChatError("the Yes/No question is empty")
        bindings: dict[str, SlotBinding] = {}
        injections: dict[str, dict[str, Any]] = {}
        for p in used:
            if stop.is_set():
                break
            yield from self._bind(request, p, rid, bindings, injections)
        embed_s = time.monotonic() - t0
        if stop.is_set():
            yield _done(rid, "abort", timings={"total_s": round(time.monotonic() - t0, 3)})
            return
        policy = self.answer.policy()
        prompt, readout = yes_no_prompt(self.renderer, policy, message.content, bindings)
        n_prompt = len(prompt.input_ids)
        if n_prompt >= self.entry.context:
            raise ChatError(f"the question renders to {n_prompt} tokens, over the context {self.entry.context}")
        if self.max_prompt_tokens is not None and n_prompt > self.max_prompt_tokens:
            raise ChatError(
                f"the question renders to {n_prompt} tokens, over this deployment's prompt limit of "
                f"{self.max_prompt_tokens} (its measured envelope)"
            )
        sources: dict[str, WriteSource] = {}
        for cid in sorted({b.connector for b in bindings.values()}):
            c = self.connectors[cid]
            objects = sorted({b.object_id for b in bindings.values() if b.connector == cid})
            sources[cid], _ = c.checked.source(c.loader, objects, self.pool.store, banked=self.scorer.reads_banks)
        yield _status(rid, "prefill", f"{n_prompt} prompt tokens", prompt_tokens=n_prompt)
        while not self._generation.acquire(timeout=0.25):  # one request at a time, generations and scores alike
            if stop.is_set():
                yield _done(rid, "abort", prompt_tokens=n_prompt, timings={"total_s": round(time.monotonic() - t0, 3)})
                return
        try:
            t_score = time.monotonic()
            read = self.scorer.score([prompt], sources, readout)  # one forward pass, not interrupted
        finally:
            self._generation.release()
        if stop.is_set():  # stopped during the pass: no result is sent
            yield _done(rid, "abort", prompt_tokens=n_prompt, timings={"total_s": round(time.monotonic() - t0, 3)})
            return
        yield _yes_no_event(rid, policy, readout.token_ids, read)
        timings = {
            "embed_s": round(embed_s, 3),
            "score_s": round(time.monotonic() - t_score, 3),
            "total_s": round(time.monotonic() - t0, 3),
        }
        yield _done(rid, "stop", prompt_tokens=n_prompt, timings=timings, injections=injections)

    def _params(self, request: ChatRequest) -> tuple[GenerationParams, bool]:
        """The request's generation parameters (unset ones from the config's defaults) and thinking mode."""
        sampling = request.sampling.model_dump(exclude_unset=True)
        defaults, cap = self.config.defaults, self.config.max_tokens_cap
        max_tokens = sampling.get("max_tokens", defaults.max_tokens)
        if max_tokens > cap:
            raise ChatError(f"sampling.max_tokens {max_tokens} is over the cap {cap}")
        params = GenerationParams(
            max_new_tokens=max_tokens,
            temperature=sampling.get("temperature", defaults.temperature),
            seed=sampling.get("seed", 0),
        )
        return params, defaults.thinking if request.thinking is None else request.thinking

    def _bind(
        self,
        request: ChatRequest,
        p: str,
        rid: str,
        bindings: dict[str, SlotBinding],
        injections: dict[str, dict[str, Any]],
    ) -> Iterator[dict[str, Any]]:
        """Resolve placeholder ``p`` into its slot binding, with its status events."""
        if p not in request.placeholders:
            raise ChatError(f"placeholder [[{p}]] has no entry in placeholders")
        given = request.placeholders[p]
        cid, input_type, value = given.connector, given.input_type, given.value
        c = self._connector(cid)
        env = c.entry.run.encoder.environment
        recipes = [r for r in (c.checked.encoder, c.checked.append_encoder) if r is not None]
        if not all(map(self.pool.warm, recipes)) and self.needs_encoder(cid, input_type, value):
            yield _status(rid, "encoder_start", f"{p}: the {env} encoder may need to start")
        yield _status(rid, "embedding", f"{p}: {cid} {input_type}")
        try:
            oid, source = self.resolve(cid, input_type, value)
        except ChatError as err:
            raise ChatError(f"placeholder {p} ({cid}, {input_type}): {err}") from err
        k = c.checked.connector.spec.k
        bindings[p] = SlotBinding(oid, cid, k)
        layers = sorted({e.layer for e in c.checked.connector.entries})
        injections[p] = {"connector": cid, "object": oid, "source": source, "k": k, "layers": layers}

    def _generate(self, rid: str, request: _Prepared, stop: threading.Event) -> Iterator[dict[str, Any]]:
        assert self.backend is not None and self.renderer is not None
        close = self.entry.receiver.thinking_close if request.thinking else None
        split = _Splitter(self.renderer.tokenizer, close)
        t_gen = time.monotonic()
        ids: list[int] = []
        first_token = first_visible = last_token = None
        finish = "length"
        stream = self.backend.stream(request.prompt, request.sources, request.params)
        try:
            for step in stream:
                if stop.is_set():
                    finish = "abort"
                    break
                now = time.monotonic()
                if first_token is None:
                    first_token = now
                    yield _status(rid, "generating", "")
                last_token = now
                ids.extend(step)
                for event in split.feed(ids, final=False):
                    first_visible = first_visible or time.monotonic()
                    yield event
            else:
                finish = "stop" if len(ids) < request.params.max_new_tokens else "length"
        finally:
            stream.close()
        if finish != "abort":
            yield from split.feed(ids, final=True)
        timings: dict[str, float | None] = {
            "embed_s": round(request.embed_s, 3),
            "ttft_s": None if first_token is None else round(first_token - t_gen, 3),
            "first_visible_s": None if first_visible is None else round(first_visible - request.t0, 3),
            "generate_s": round(time.monotonic() - t_gen, 3),
            "total_s": round(time.monotonic() - request.t0, 3),
            "tok_per_s": None,
        }
        if first_token is not None and last_token is not None and last_token > first_token and len(ids) > 1:
            timings["tok_per_s"] = round((len(ids) - 1) / (last_token - first_token), 2)
        yield _done(
            rid,
            finish,
            prompt_tokens=len(request.prompt.input_ids),
            completion_tokens=len(ids),
            timings=timings,
            injections=request.injections,
            closed=split.closed,
        )


class _Placeholder(BaseModel):
    model_config = ConfigDict(extra="ignore", strict=True)
    connector: str
    input_type: str
    value: str


class _Message(BaseModel):
    model_config = ConfigDict(extra="ignore", strict=True)
    role: Literal["user", "assistant"]
    content: str


class _Sampling(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)
    temperature: float = Field(default=0.0, ge=0.0, le=2.0)
    max_tokens: int = Field(default=1, ge=1)
    seed: int = Field(default=0, ge=0, lt=2**63)


class ChatRequest(BaseModel):
    """The body of ``/api/chat`` (the API contract: ``examples/guides/chat.md``).

    Attributes:
        messages: the conversation, oldest first, ending with a user turn; user turns may hold ``[[id]]``.
        placeholders: id → its connector, input type and value (other fields, e.g. a label, are ignored).
        thinking: thinking mode (None: the config's default).
        system: a system message ("" for none).
        sampling: ``temperature``, ``max_tokens`` and ``seed``; unset ones take the config's defaults (``seed`` 0).
        readout: ``generate`` (a reply), or ``yes_no``: the last user turn alone scored as a Yes/No question
            (``ChatService`` with an answer convention; the other turns, ``system``, ``thinking`` and ``sampling``
            unused).
    """

    model_config = ConfigDict(extra="ignore", strict=True)
    messages: list[_Message] = Field(min_length=1)
    placeholders: dict[str, _Placeholder] = Field(default_factory=dict)
    thinking: bool | None = None
    system: str = ""
    sampling: _Sampling = _Sampling()
    readout: Literal["generate", "yes_no"] = "generate"

    def conversation(self, max_placeholders: int) -> tuple[tuple[Message, ...], list[str]]:
        """Return the renderer's messages (each ``[[id]]`` as the slot ``<SLOT:id>``) and the ids used, in order.

        Raises:
            ChatError: if a text holds ``<SLOT:``, a placeholder is outside a user turn, the last turn is not the
                user's, or more than ``max_placeholders`` are used.
        """
        out = [Message("system", self.system)] if self.system else []
        used: list[str] = []
        for i, m in enumerate(self.messages):
            if "<SLOT:" in m.content or "<SLOT:" in self.system:
                raise ChatError(f"message {i}: '<SLOT:' is reserved; a placeholder is written [[id]]")
            ids = PLACEHOLDER.findall(m.content)
            if ids and m.role != "user":
                raise ChatError(f"message {i}: placeholders go in user turns only")
            used += [p for p in dict.fromkeys(ids) if p not in used]
            out.append(Message(m.role, PLACEHOLDER.sub(r"<SLOT:\1>", m.content)))
        if out[-1].role != "user":
            raise ChatError("the last message must be the user's")
        if len(used) > max_placeholders:
            raise ChatError(f"{len(used)} placeholders; the limit is {max_placeholders}")
        return tuple(out), used


@dataclass(frozen=True)
class _Prepared:
    """A request ready to generate."""

    prompt: RenderedPrompt
    sources: Mapping[str, WriteSource]
    params: GenerationParams
    thinking: bool
    injections: dict[str, dict[str, Any]]
    t0: float
    embed_s: float


class _Splitter:
    """Generated ids → reasoning / content text deltas, decoded by the one decoding (``generated_text``).

    With a thinking close, the text before its first occurrence is reasoning and the rest content; without one, all
    is content. Text is sent as it grows; a tail that may still change (an incomplete UTF-8 sequence, or the start of
    the thinking close) is held back until the next step or the end. Leading whitespace of each channel is not sent.
    """

    def __init__(self, tokenizer: Any, close: str | None) -> None:
        self.tokenizer, self.close = tokenizer, close
        self.sent = {"reasoning": "", "content": ""}
        self.closed = close is None

    def feed(self, ids: list[int], *, final: bool) -> Iterator[dict[str, Any]]:
        text = generated_text(self.tokenizer, ids)
        if not final and text.endswith("�"):
            return
        parts = {"reasoning": "", "content": text}
        if self.close is not None:
            at = text.find(self.close)
            self.closed = at >= 0
            if at >= 0:
                parts = {"reasoning": text[:at], "content": text[at + len(self.close) :]}
            else:
                hold = next((n for n in range(len(self.close) - 1, 0, -1) if text.endswith(self.close[:n])), 0)
                parts = {"reasoning": text[: len(text) - hold] if not final else text, "content": ""}
        for channel in ("reasoning", "content"):
            now = parts[channel].lstrip()
            sent = self.sent[channel]
            new = now[len(sent) :] if now.startswith(sent) else now[len(os.path.commonprefix([now, sent])) :]
            if new:
                self.sent[channel] = now
                yield {"type": channel, "delta": new}


def _status(rid: str, stage: str, detail: str, **extra: Any) -> dict[str, Any]:
    return {"type": "status", "stage": stage, "detail": detail, "request_id": rid, **extra}


def _yes_no_event(rid: str, policy: Answering, ids: tuple[int, ...], read: Any) -> dict[str, Any]:
    """Return the ``yes_no`` event of a one-prompt next-token readout ``read`` of the answers ``ids``.

    It holds the answers' full-softmax log-probabilities, the suites' score ``logp_yes - logp_no``
    (``evaluation.runners.log_odds``) and the pair-normalized P(yes) / (P(yes) + P(no)). A value that is not finite
    (an answer of probability 0 in the state dtype) is null, never a JSON ``-Infinity``.
    """
    (logp_yes, logp_no), score = (float(x) for x in answer_log_probs(read)[0]), float(log_odds(read)[0])

    def finite(x: float) -> float | None:
        return x if math.isfinite(x) else None

    pair = None if math.isnan(score) else 1.0 / (1.0 + math.exp(-score)) if score > _EXP_FLOOR else math.exp(score)
    yes_id, no_id = ids
    return {
        "type": "yes_no",
        "request_id": rid,
        "instruction": policy.instruction,
        "prefix": policy.prefix,
        "yes": policy.yes,
        "no": policy.no,
        "yes_id": yes_id,
        "no_id": no_id,
        "logp_yes": finite(logp_yes),
        "logp_no": finite(logp_no),
        "score": finite(score),
        "pair_normalized": pair,
    }


def _done(
    rid: str,
    finish: str,
    *,
    prompt_tokens: int = 0,
    completion_tokens: int = 0,
    timings: Mapping[str, float | None],
    injections: Mapping[str, Any] | None = None,
    closed: bool = False,
) -> dict[str, Any]:
    return {
        "type": "done",
        "request_id": rid,
        "finish_reason": finish,
        "usage": {"prompt_tokens": prompt_tokens, "completion_tokens": completion_tokens},
        "timings": dict(timings),
        "injections": dict(injections or {}),
        "thinking_closed": closed,
    }
