"""The chat service: one receiver's conversations with objects in them, everything but HTTP (``chat.server``).

A request is a whole conversation (the client keeps it): user turns may hold placeholders ``[[P1]]``, each bound to a
connector and an input (an object id of the connector's domain, or a raw value). The service serves it with the
package's own pieces, in this order:

1. resolution: each placeholder becomes an object of its connector's input loader (``chat.encoding`` for a new one:
   an object id the run's cached embeddings hold is served from them; any other, and every raw value, is encoded live
   into an ordinary embedding artifact; both go through the one loader, with the recipe and consumed-value checks of
   ``encoders.loader``);
2. rendering: the conversation, each ``[[P]]`` as the slot ``<SLOT:P>``, through the receiver's one renderer
   (``receivers.render``; multi-turn by the model's own chat template, thinking per the receiver config);
3. writes: per connector, the source its backend takes (live connector or a write bank of the request's objects),
   from the one assembly ``run.suite.checked_connector``, so the writes are the suite stage's;
4. generation: the backend's ``stream`` (``receivers.base.GenerationBackend``), one request at a time; each engine
   step's ids are decoded by ``receivers.base.generated_text`` and sent as they grow, split into reasoning and content
   at the receiver's ``thinking_close`` in thinking mode.

A request with ``readout: "yes_no"`` is scored instead of generated, as a ``yes_no`` suite scores (served only with an
answer convention, ``answer``): its last user turn alone (no system message, no earlier turn, only that turn's
placeholders) is rendered by ``evaluation.runners.yes_no_prompt``, thinking off, and the next token's log-probabilities
of the convention's two answers are read under the full softmax (one ``yes_no`` event). It is offered only when the
receiver's ``score`` backend is its ``generate`` backend (``hf``: Gemma), and the score runs on the loaded model through
a scoring view of it (``receivers.open_scoring``, its batches right-padded as the release suites' are); a receiver
scored by another engine (Kimi K2.6: ``kimi-stream``, generated by ``kimi-vllm``) does not offer it.

A service with ``serial_requests`` (a measured local envelope's concurrency 1) serves one whole request at a time
instead: a request's resolution waits until the request before has finished, so no live encoding overlaps a generation.

A request is stopped at any stage by its stop event (``/api/stop``, a client that goes away): before generation
nothing reaches the receiver; during it the stream is closed, which cancels it. A stop that arrives during a live
encoding takes effect when that encoding returns (the encoding itself is not interrupted; its artifact is kept).

Chat writes only to its own store, the encoder pool's (``EncoderPool.store``: ``$LIP_DATA/chat/store`` by default, a
disposable scratch store): staged inputs, live embeddings and write banks. The workspace's store is read only
(checkpoints, the runs' cached embeddings, the domain tables). Errors are events, never a silent
substitute: an unknown connector or input, a connector whose checkpoint pin is missing or refused, an object the
loader refuses or an encoding that failed.
"""

